export type MessageKey = keyof (typeof messages)['zh']

type I18nContextValue = {
  prefs: LanguagePrefs
  setPrefs: (prefs: LanguagePrefs) => void
  language: UiLanguage
  t: (key: MessageKey) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({
  children,
  value,
  onChange,
}: {
  children: ReactNode
  value?: LanguagePrefs
  onChange?: (prefs: LanguagePrefs) => void
}) {
  const [internal, setInternal] = useState<LanguagePrefs>(value ?? loadLanguagePrefs)
  const prefs = value ?? internal

  useEffect(() => subscribeLanguagePrefs(setInternal), [])

  useEffect(() => {
    document.documentElement.lang = prefs.uiLang === 'zh' ? 'zh-CN' : prefs.uiLang
  }, [prefs.uiLang])

  useEffect(() => {
    const media = window.matchMedia?.('(prefers-color-scheme: dark)')
    const applyTheme = () => {
      const dark = prefs.theme === 'dark' || (prefs.theme === 'system' && media?.matches === true)
      document.documentElement.classList.toggle('dark', dark)
    }
    applyTheme()
    if (prefs.theme !== 'system' || !media) return
    media.addEventListener('change', applyTheme)
    return () => media.removeEventListener('change', applyTheme)
  }, [prefs.theme])

  const context = useMemo<I18nContextValue>(
    () => ({
      prefs,
      language: prefs.uiLang,
      setPrefs: (next) => {
        if (!value) setInternal(next)
        persistLanguagePrefs(next)
        onChange?.(next)
      },
      t: (key) => messages[prefs.uiLang][key],
    }),
    [onChange, prefs, value],
  )

  return <I18nContext.Provider value={context}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside I18nProvider')
  return context
}

